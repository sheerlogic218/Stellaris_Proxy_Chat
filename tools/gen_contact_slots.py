"""Generates the contact list for the Voice Chat menu (event proxychat.40).

Stellaris localisation can't loop over countries, so each player empire is saved
as a global event target proxychat_p<id>. When the menu opens, its immediate block
copies the viewer's contacts, in order, into event targets proxychat_c1..cN and
counts them. The description is then the variant written for N names, and each
name is a plain [proxychat_cK.GetName] in the event's own text.

(An earlier version printed the names from scripted loc. Event targets don't
resolve inside nested scripted-loc text, so every line showed the viewer's own name.)

  python tools/gen_contact_slots.py [--slots 64]

Writes (overwrites) three files in mod/proxychat. Re-run after changing --slots.
"""

import argparse
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent / "mod" / "proxychat"
HEADER = "# GENERATED by tools/gen_contact_slots.py, do not edit by hand.\n"
NL = "\\n"  # a literal \n inside Stellaris localisation strings
COUNT = "proxychat_contact_count"
# Federations with association status the menu offers (proxychat_collect_federations saves this many)
ASSOC_SLOTS = 4
KEY = "[Root.proxychat_ka]-[Root.proxychat_kb]-[Root.proxychat_kc]"


def effects(slots):
    out = [HEADER, "# Country scope (a player empire with a proxychat_id).",
           "# Saves it as the global event target proxychat_p<id>.",
           "proxychat_save_slot_target = {"]
    for i in range(1, slots + 1):
        keyword = "if" if i == 1 else "else_if"
        out.append(f"\t{keyword} = {{")
        out.append(f"\t\tlimit = {{ check_variable = {{ which = proxychat_id value = {i} }} }}")
        out.append(f"\t\tsave_global_event_target_as = proxychat_p{i}")
        out.append("\t}")
    out.append("}")

    out += ["", "# Country scope = the empire opening the Voice Chat menu (from proxychat.40's immediate).",
            f"# Copies each player empire it has communications with into event targets",
            f"# proxychat_c1, proxychat_c2... in id order, and counts them in {COUNT}.",
            "proxychat_collect_contacts = {",
            f"\tset_variable = {{ which = {COUNT} value = 0 }}"]
    for i in range(1, slots + 1):
        target = f"event_target:proxychat_p{i}"
        out += ["\tif = {",
                "\t\tlimit = {",
                f"\t\t\texists = {target}",
                f"\t\t\tNOT = {{ is_same_value = {target} }}",
                f"\t\t\thas_communications = {target}",
                f"\t\t\t{target} = {{ proxychat_is_player = yes }}",
                "\t\t}",
                f"\t\tchange_variable = {{ which = {COUNT} value = 1 }}"]
        # The count is at most i here, so only positions 1..i are possible
        for n in range(1, i + 1):
            keyword = "if" if n == 1 else "else_if"
            out.append(f"\t\t{keyword} = {{ limit = {{ check_variable = {{ which = {COUNT} value = {n} }} }} "
                       f"{target} = {{ save_event_target_as = proxychat_c{n} }} }}")
        out.append("\t}")
    out.append("}")
    return "\n".join(out) + "\n"


def event(slots):
    out = [HEADER, "namespace = proxychat", "",
           "# ---- Voice Chat menu (from the main-screen button) -----------------------",
           "# Root = the player who clicked it. The description lists every player empire",
           "# Root has communications with: immediate collects them into proxychat_c1..cN",
           f"# ({COUNT} = N), and the description variant for N names is shown.",
           "#",
           "# PROXYCHAT|HOME|<game key>|<id>          back to our own embassy channel",
           "# PROXYCHAT|GALCOM_JOIN|<game key>|<id>   into the Galactic Community channel",
           "# PROXYCHAT|FED_JOIN|<game key>|<id>|<federation id>|<M or A>|<federation name>",
           "#     into our own federation's channel (M), or one we have association status with (A):",
           f"#     proxychat_collect_federations saves up to {ASSOC_SLOTS} of those as proxychat_f1...",
           "country_event = {",
           "\tid = proxychat.40",
           "\ttitle = proxychat.40.name",
           "\tpicture = GFX_evt_communication_event",
           "\tis_triggered_only = yes",
           "",
           "\timmediate = {",
           "\t\tproxychat_collect_contacts = yes",
           "\t\tproxychat_collect_federations = yes",
           "\t}",
           "",
           "\t# Exactly one of these matches",
           "\tdesc = {",
           f"\t\ttrigger = {{ NOT = {{ check_variable = {{ which = {COUNT} value > 0 }} }} }}",
           "\t\ttext = proxychat.40.desc.0",
           "\t}"]
    for n in range(1, slots + 1):
        out += ["\tdesc = {",
                f"\t\ttrigger = {{ check_variable = {{ which = {COUNT} value = {n} }} }}",
                f"\t\ttext = proxychat.40.desc.{n}",
                "\t}"]
    out += ["",
            "\toption = {",
            "\t\tname = proxychat.40.home",
            "\t\thidden_effect = {",
            '\t\t\tlog = "PROXYCHAT|HOME|[Root.proxychat_ka]-[Root.proxychat_kb]-[Root.proxychat_kc]|[Root.proxychat_id]"',
            "\t\t}",
            "\t}",
            "\toption = {",
            "\t\tname = proxychat.40.galcom",
            "\t\ttrigger = {",
            "\t\t\tis_galactic_community_formed = yes",
            "\t\t\tis_galactic_community_member = yes",
            "\t\t}",
            "\t\thidden_effect = {",
            '\t\t\tlog = "PROXYCHAT|GALCOM_JOIN|[Root.proxychat_ka]-[Root.proxychat_kb]-[Root.proxychat_kc]|[Root.proxychat_id]"',
            "\t\t}",
            "\t}",
            "\toption = {",
            "\t\tname = proxychat.40.federation",
            "\t\ttrigger = { has_federation = yes }",
            "\t\thidden_effect = {",
            f'\t\t\tlog = "PROXYCHAT|FED_JOIN|{KEY}|[Root.proxychat_id]|[Root.proxychat_fid]|M|[Root.Federation.GetName]"',
            "\t\t}",
            "\t}"]
    for k in range(1, ASSOC_SLOTS + 1):
        target = f"proxychat_f{k}"
        out += ["\toption = {",
                f"\t\tname = proxychat.40.assoc.{k}",
                f"\t\ttrigger = {{ check_variable = {{ which = proxychat_assoc_count value > {k - 1} }} }}",
                "\t\thidden_effect = {",
                f'\t\t\tlog = "PROXYCHAT|FED_JOIN|{KEY}|[Root.proxychat_id]|[{target}.proxychat_fid]|A|[{target}.Federation.GetName]"',
                "\t\t}",
                "\t}"]
    out += ["\toption = {",
            "\t\tname = proxychat.40.close",
            "\t}",
            "}"]
    return "\n".join(out) + "\n"


def localisation(slots):
    intro = f"Player empires we have communications with:{NL}{NL}"
    out = ["l_english:", f' proxychat.40.desc.0:0 "{intro}None yet."']
    for n in range(1, slots + 1):
        names = NL.join(f"- §H[proxychat_c{k}.GetName]§!" for k in range(1, n + 1))
        out.append(f' proxychat.40.desc.{n}:0 "{intro}{names}"')
    for k in range(1, ASSOC_SLOTS + 1):
        out.append(f' proxychat.40.assoc.{k}:0 "Join the [proxychat_f{k}.Federation.GetName] Voice Channel (associate)"')
    return "\n".join(out) + "\n"


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--slots", type=int, default=64)
    args = p.parse_args()
    files = {
        MOD / "common/scripted_effects/proxychat_slots_generated.txt": (effects(args.slots), "utf-8"),
        MOD / "events/proxychat_menu_generated.txt": (event(args.slots), "utf-8"),
        # Localisation must be UTF-8 with BOM
        MOD / "localisation/english/proxychat_contacts_generated_l_english.yml": (localisation(args.slots), "utf-8-sig"),
    }
    for path, (text, encoding) in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding=encoding, newline="\n")
        print(f"wrote {path.relative_to(MOD)}")
    # Left over from the scripted-loc version
    stale = MOD / "common/scripted_loc/proxychat_contacts_generated.txt"
    if stale.exists():
        stale.unlink()
        print(f"removed {stale.relative_to(MOD)}")


if __name__ == "__main__":
    main()
